--
-- Не більше однієї події `RECOVERED` на позику: другий і конкурентний `recover` отримують порушення
-- цього індексу (API → 409 `LOAN_ALREADY_RECOVERED`), а не другу подію чи другу зміну стану
-- примірника. Це однократність ефекту, а не повтор успішної відповіді.
--
-- Частковий індекс, тож Prisma про нього не знає (як і `one_active_loan_per_copy`): у `schema.prisma`
-- його немає, а `prisma migrate diff` його не вимагає.
--
-- Міграція лише додає індекс. Вона не читає й не переписує жодного `Copy`/`Loan`, не створює жодної
-- події: `LoanEvent` до цього кроку ніхто не пише, тож таблиця порожня, а старі `LOST`-позики лишаються
-- без подій і відновлюються без вигаданої «дати втрати».
CREATE UNIQUE INDEX "one_recovery_per_loan" ON "LoanEvent" ("loanId") WHERE "type" = 'RECOVERED';
